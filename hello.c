#include<stdio.h>
int main()
{
    int days;
    scanf("%d",&days);
    switch(days)
        {case 1:
        {printf("monday");
    break;}
         case 2:
        {printf("tuesday");
    break;}
         case 3:
        {printf("wednesday");
    break;}
         case 4:
        {printf("thursaday");
      break;  }
         case 5:
        {printf("friday");
    break;}
         Default:
             printf("not a day");
    }
}

    
